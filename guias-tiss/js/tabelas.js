// Maior valor aceito por procedimento/item: st_decimal8-2 na 4.01.00, st_decimal10-2 depois.
TISS.maxProcedureValue = function (version) {
  return version === '4.01.00' ? 999999.99 : 99999999.99
}
TISS.maxItemValue = TISS.maxProcedureValue

TISS.label = function (options, value) {
  const found = options.find(function (o) { return o.value === value })
  return found ? found.label : value
}
